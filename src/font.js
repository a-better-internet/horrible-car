const MISSING = [0x7f, 0x41, 0x41, 0x41, 0x7f];

export const GLYPH_W = 5;
export const GLYPH_H = 7;
/** One blank column between characters. */
export const ADVANCE = GLYPH_W + 1;

/** Rendered width of `str` at the given scale. */
export const textWidth = (str, scale = 1) =>
  (str.length * ADVANCE - 1) * scale;

/**
 * Draw text with the top-left corner at (x, y).
 * @param {CanvasRenderingContext2D} ctx
 * @param {string} str
 * @param {number} x
 * @param {number} y
 * @param {string} color
 * @param {number} scale integer pixel scale
 */
export function text(ctx, str, x, y, color, scale = 1) {
  ctx.fillStyle = color;
  const s = String(str).toUpperCase();
  let px = Math.round(x);
  const py = Math.round(y);
  for (let i = 0; i < s.length; i++) {
    const g = G[s[i]] || MISSING;
    if (s[i] !== ' ') {
      for (let col = 0; col < GLYPH_W; col++) {
        const bits = g[col];
        if (!bits) continue;
        // Coalesce vertical runs into one fillRect: far fewer draw calls.
        let row = 0;
        while (row < GLYPH_H) {
          if (bits & (1 << row)) {
            let run = 1;
            while (row + run < GLYPH_H && (bits & (1 << (row + run)))) run++;
            ctx.fillRect(px + col * scale, py + row * scale, scale, run * scale);
            row += run;
          } else {
            row++;
          }
        }
      }
    }
    px += ADVANCE * scale;
  }
}

/** Draw text centred on `cx`. */
export function textCentered(ctx, str, cx, y, color, scale = 1) {
  text(ctx, str, Math.round(cx - textWidth(str, scale) / 2), y, color, scale);
}

/** Draw text right-aligned so it ends at `rx`. */
export function textRight(ctx, str, rx, y, color, scale = 1) {
  text(ctx, str, Math.round(rx - textWidth(str, scale)), y, color, scale);
}

/** Text with a one-pixel drop shadow, for anything drawn over the road. */
export function textShadow(ctx, str, x, y, color, scale = 1, shadow = '#000') {
  text(ctx, str, x + scale, y + scale, shadow, scale);
  text(ctx, str, x, y, color, scale);
}

export function textCenteredShadow(ctx, str, cx, y, color, scale = 1, shadow = '#000') {
  const x = Math.round(cx - textWidth(str, scale) / 2);
  textShadow(ctx, str, x, y, color, scale, shadow);
}
